<?php

namespace App\Console\Commands;

use App\Models\Addons\Asset;
use App\Models\Addons\AssetGroup;
use Illuminate\Console\Command;

class ExportAssetMasterData extends Command
{
    protected $signature = 'addons:asset:export-master
        {--company-id= : Company ID to export (required)}
        {--output= : Output path (default: database/seeders/data/asset_master_company_{id}.php)}';

    protected $description = 'Export asset groups and assets from DB into a seeder data PHP file.';

    public function handle(): int
    {
        $companyId = $this->option('company-id') !== null ? (int) $this->option('company-id') : null;

        if (! $companyId) {
            $this->error('--company-id wajib.');

            return self::INVALID;
        }

        $groups = AssetGroup::withoutGlobalScopes()
            ->where('company_id', $companyId)
            ->with(['assetAccount', 'contraAsset'])
            ->orderBy('id')
            ->get()
            ->map(fn (AssetGroup $group) => [
                'name' => $group->name,
                'description' => $group->description,
                'useful_life_months' => $group->useful_life_months,
                'default_method' => $group->default_method?->value,
                'asset_account_name' => $group->assetAccount?->name,
                'contra_account_name' => $group->contraAsset?->name,
            ])
            ->values()
            ->all();

        $assets = Asset::withoutGlobalScopes()
            ->where('company_id', $companyId)
            ->with('group')
            ->orderBy('id')
            ->get()
            ->map(fn (Asset $asset) => [
                'group_name' => $asset->group?->name,
                'asset_code' => $asset->asset_code,
                'name' => $asset->name,
                'acquisition_date' => $asset->acquisition_date->format('Y-m-d'),
                'acquisition_cost' => $asset->acquisition_cost,
                'useful_life_months' => $asset->useful_life_months,
                'salvage_value' => $asset->salvage_value,
                'depreciation_method' => $asset->depreciation_method?->value,
                'status' => $asset->status?->value,
                'meta' => $asset->meta,
            ])
            ->values()
            ->all();

        $payload = [
            'groups' => $groups,
            'assets' => $assets,
        ];

        $output = $this->option('output')
            ?? database_path("seeders/data/asset_master_company_{$companyId}.php");

        $exported = var_export($payload, true);

        $contents = <<<PHP
<?php

/**
 * Master data snapshot for asset groups & assets (company_id={$companyId}).
 * Generated by: php artisan addons:asset:export-master --company-id={$companyId}
 */
return {$exported};

PHP;

        if (! is_dir(dirname($output))) {
            mkdir(dirname($output), 0755, true);
        }

        file_put_contents($output, $contents);

        $this->info('Exported ' . count($groups) . ' groups and ' . count($assets) . " assets to {$output}");

        return self::SUCCESS;
    }
}
